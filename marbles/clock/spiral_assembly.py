#!/usr/bin/env python3
"""Spiral run assembly mockup (WIP): writes spiral_assembly.scad from spiral_run.py's real geometry and renders views.

The sheet is drawn PULLED DOWN as an idealised slinky: each strip (between one lap of the cut and the next) sits at a
height that falls linearly along the spiral, DROP in total from the first lap to the solid centre. So the step at
every cut is DROP / laps. Shown: the top 2020 beam under the mount edge, the sheet, the entry flange on its 2020 post
with the incoming wire tunnel, the centre guide on the solid centre, the exit flange under it with the outgoing
tunnel, and balls on the run.

    python3 marbles/clock/spiral_assembly.py                  # ply3, DROP 100
    python3 marbles/clock/spiral_assembly.py --drop 150 --material birch3
"""
import argparse
import math
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
import spiral_run as S  # noqa: E402

THICK = {"ply3": 2.63, "mdf3": 2.82, "birch3": 3.0}


def poly2d(pts):
    return "polygon(" + str([[round(x, 3), round(y, 3)] for x, y in pts]) + ");"


def strips(cut_t, z_of, T, t_end):
    """polyhedra for the strips: outer edge = cut at t, inner edge = cut at t + 2 pi, both at z(t)"""
    out = []
    ts = [t for t in cut_t if t <= t_end - 2 * math.pi]
    seg = 40
    for i0 in range(0, len(ts) - 1, seg):
        part = ts[i0:i0 + seg + 1]
        if len(part) < 2:
            continue
        pts, faces = [], []
        for t in part:
            o = S.ellipse_pt(S.A0 - S.k * t, S.B0 - S.k * t, t)
            n = S.ellipse_pt(S.A0 - S.k * (t + 2 * math.pi), S.B0 - S.k * (t + 2 * math.pi), t + 2 * math.pi)
            z = z_of(t)
            pts += [(o[0], o[1], z), (n[0], n[1], z), (o[0], o[1], z + T), (n[0], n[1], z + T)]
        m = len(part)
        for j in range(m - 1):
            a, b = 4 * j, 4 * (j + 1)
            faces += [[a, b, b + 1, a + 1], [a + 2, a + 3, b + 3, b + 2], [a, a + 2, b + 2, b], [a + 1, b + 1, b + 3, a + 3]]
        faces += [[0, 1, 3, 2], [4 * (m - 1), 4 * (m - 1) + 2, 4 * (m - 1) + 3, 4 * (m - 1) + 1]]
        out.append("polyhedron(points=" + str([[round(c, 3) for c in p] for p in pts]) + ", faces=" + str(faces) + ");")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--material", default="ply3")
    ap.add_argument("--spacer", type=float, default=8.0, help="entry guide's height above the sheet (2 M5 nuts)")
    ap.add_argument("--out", type=Path, default=HERE / "spiral_assembly.scad")
    a = ap.parse_args()
    T = THICK[a.material]
    B = S.build()
    t_end = B["t_end"]
    S.k = S.PITCH / (2 * math.pi)
    z_of = S.z_of                                              # DROP_REV per revolution, held by the stair arms
    cut_t = S._ts(t_end, S.PITCH)
    zc = z_of(t_end)
    L = []
    L.append(f"// GENERATED by spiral_assembly.py ({a.material}, {S.DROP_REV:g} per lap on the stair arms): WIP mockup")
    L.append("$fn = 32;")
    # top beam under the mount edge
    L.append("color(\"silver\") translate([0, 0, %g]) cube([300, 20, 20]);" % T)     # edge beam ON TOP of the sheet
    # frame: stock minus the region inside the first lap, at z 0
    first = [S.ellipse_pt(S.A0 - S.k * t, S.B0 - S.k * t, t) for t in cut_t if t <= 2 * math.pi]
    holes_xy = [h for h, lab in B["holes"] if lab == "mount M5"]
    L.append("color(\"burlywood\") translate([0, 0, 0]) linear_extrude(%g) difference() { square([300, 300]); %s %s }"
             % (T, poly2d(first), " ".join(poly2d(h) for h in holes_xy)))
    L.append("color(\"burlywood\") {")
    L += strips(cut_t, z_of, T, t_end)
    L.append("}")
    # solid centre
    last = [S.ellipse_pt(S.A0 - S.k * t, S.B0 - S.k * t, t) for t in cut_t if t >= t_end - 2 * math.pi]
    cen_holes = [h for h, lab in B["holes"] if lab != "mount M5"]
    L.append("color(\"tan\") translate([0, 0, %g]) linear_extrude(%g) difference() { %s %s }"
             % (zc, T, poly2d(last), " ".join(poly2d(h) for h in cen_holes)))
    # centre guide on top
    g = B["guide"]
    L.append("color(\"peru\") translate([0, 0, %g]) linear_extrude(%g) difference() { %s %s }"
             % (zc + T, T, poly2d(list(g.exterior.coords)), " ".join(poly2d(list(r.coords)) for r in g.interiors)
                + " ".join("translate([%g, %g]) circle(d = 5);" % b for b in B["bolts"])))
    # exit flange under the centre + outgoing tunnel straight down
    ex = B["exit"]
    L.append("color(\"sienna\") translate([%g, %g, %g]) linear_extrude(%g) difference() { %s %s }"
             % (S.CX, S.CY, zc - T, T, poly2d(list(ex.exterior.coords)), " ".join(poly2d(list(r.coords)) for r in ex.interiors)))
    for ang in (45, 135, 225, 315):
        u = (math.cos(math.radians(ang + S.EXIT_REPORT[0])), math.sin(math.radians(ang + S.EXIT_REPORT[0])))
        L.append("color(\"silver\") translate([%g, %g, %g]) cylinder(d = %g, h = 120);"
                 % (S.CX + S.TUN_RW * u[0], S.CY + S.TUN_RW * u[1], zc - T - 120, S.TUN_WIRE))
    for kz in (30, 70, 110):
        L.append("color(\"silver\") translate([%g, %g, %g]) rotate_extrude() translate([%g, 0]) circle(d = %g);"
                 % (S.CX, S.CY, zc - T - kz, S.TUN_RW + S.TUN_WIRE, S.TUN_WIRE))
    # guide bolts down through to a tie (sketch)
    for bx, by in B["bolts"]:
        L.append("color(\"dimgray\") translate([%g, %g, %g]) { cylinder(d = 5, h = %g); translate([0, 0, %g]) cylinder(d = 9.5, h = 2.75); }"
                 % (bx, by, zc - T - 25, 25 + 3 * T, 25 + 3 * T))
    # stair arms (the X) under the sheet, each on a 2020 along its bottom edge
    for phi, (arm, steps, m5) in B["arms"].items():
        L.append("color(\"peru\") rotate([0, 0, 0]) translate([%g, %g, 0]) rotate([0, 0, %g]) rotate([90, 0, 0]) translate([0, 0, %g]) "
                 "linear_extrude(%g) difference() { %s %s }"
                 % (S.CX, S.CY, phi, -T / 2, T, poly2d(list(arm.exterior.coords)), " ".join(poly2d(list(r.coords)) for r in arm.interiors)))
        L.append("color(\"silver\") translate([%g, %g, 0]) rotate([0, 0, %g]) translate([%g, %g, %g]) cube([%g, 20, 20]);"
                 % (S.CX, S.CY, phi, S.ARM_S0, T / 2, B["z_floor"], arm.bounds[2] - S.ARM_S0))
    # entry guide on spacers above the frame
    eg = B["entry_guide"]
    L.append("color(\"sienna\") translate([0, 0, %g]) linear_extrude(%g) difference() { %s %s }"
             % (T + a.spacer, T, poly2d(list(eg.exterior.coords)), " ".join(poly2d(list(r.coords)) for r in eg.interiors)))
    for q in B["entry_m5"]:
        L.append("color(\"dimgray\") translate([%g, %g, %g]) cylinder(d = 8, h = %g, $fn = 6);" % (q[0], q[1], T, a.spacer))
    # incoming wire tunnel along the beam's face, at shelf level, ending where the cut starts
    p0 = B["cut"][0]
    yc = p0[1] + S.BALL_R
    for ang in (45, 135, 225, 315):
        u = (math.cos(math.radians(ang)), math.sin(math.radians(ang)))
        L.append("color(\"silver\") translate([%g, %g, %g]) rotate([0, -90, 0]) cylinder(d = %g, h = 130);"
                 % (p0[0] - 10, yc + S.TUN_RW * u[0], T + S.NO_DROP_AXIS + S.TUN_RW * u[1], S.TUN_WIRE))
    x_f = p0[0] - 10
    v0 = S.NO_DROP_AXIS
    # balls: queue in the tunnel, a few on the shelves, one in the guide channel
    balls = [(x_f - 25 - 20 * i, yc, T + v0 - (v0 - S.BALL_R)) for i in range(3)]
    for frac in (0.02, 0.18, 0.37, 0.55, 0.74, 0.9):
        t = frac * (t_end - 2 * math.pi)
        o = S.ellipse_pt(S.A0 - S.k * t, S.B0 - S.k * t, t)
        n = S.ellipse_pt(S.A0 - S.k * (t + 0.01), S.B0 - S.k * (t + 0.01), t + 0.01)
        d = math.dist(o, n)
        nx, ny = -(n[1] - o[1]) / d, (n[0] - o[0]) / d
        balls.append((o[0] + S.BALL_R * nx, o[1] + S.BALL_R * ny, z_of(t) + T + S.BALL_R))
    pth = B["path"]
    for q in (pth[len(pth) // 3], pth[-1]):
        balls.append((q[0], q[1], zc + T + S.BALL_R - (0 if q is pth[len(pth) // 3] else 6)))
    for b in balls:
        L.append("color(\"steelblue\") translate([%g, %g, %g]) sphere(d = 19.05);" % b)
    a.out.write_text("\n".join(L) + "\n")
    print(f"wrote {a.out.name}: {a.material}, {S.DROP_REV:g} per lap, centre {-S.z_of(t_end):.1f} below the frame; arms' floor {-B['z_floor']:.1f}")


if __name__ == "__main__":
    main()
